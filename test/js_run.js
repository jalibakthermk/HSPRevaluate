const fs=require('fs'), H=require('../src/hspr-core.js');
const g=f=>H.toGrid(H.parseIES(fs.readFileSync(f,'utf8')));
let t=Date.now();
const lb=H.assessLB(g('lb.ies'),g('lb_rh.ies'),0.65,1.4);
lb.rows.forEach(r=>console.log('LB',r.key,+r.value.toFixed(3),+r.points.toFixed(3)));
console.log('LB score',lb.score.toFixed(2),lb.rank);
const gh=g('hb.ies'); const hb=H.assessHB(gh,gh,0.7,1.3);
hb.rows.forEach(r=>console.log('HB',r.key,+r.value.toFixed(3),+r.points.toFixed(3)));
console.log('HB score',hb.score.toFixed(2),hb.rank,'ms',Date.now()-t);
console.log(JSON.stringify(H.system({lb:lb.score,hb:hb.score})));
